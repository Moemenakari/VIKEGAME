export function goalText(goal: MainGoal): string {
  switch (goal.kind) {
    case 'building':
      return goal.level <= 1
        ? t('goalBuild', { b: bName(goal.building) })
        : t('goalUpgrade', { b: bName(goal.building), n: goal.level });
    case 'troops':
      return t('goalTroops', { n: goal.count });
    case 'barrow':
      return t('goalBarrow', { n: goal.level });
  }
}

